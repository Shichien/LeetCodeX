import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(root, "THIRD_PARTY_NOTICES.md");
const maxBuffer = 32 * 1024 * 1024;

const cargo = JSON.parse(execFileSync("cargo", ["metadata", "--locked", "--format-version", "1"], {
  cwd: root,
  encoding: "utf8",
  maxBuffer,
}));
const pnpmCommand = process.platform === "win32" ? "pnpm.cmd" : "pnpm";
const npmLicenses = JSON.parse(execFileSync(pnpmCommand, ["--dir", "web", "licenses", "list", "--prod", "--json"], {
  cwd: root,
  encoding: "utf8",
  maxBuffer,
}));

const records = [];
for (const pkg of cargo.packages.filter((pkg) => pkg.source !== null)) {
  records.push({
    ecosystem: "Rust",
    name: pkg.name,
    version: pkg.version,
    license: pkg.license || "UNKNOWN",
    authors: Array.isArray(pkg.authors) ? pkg.authors.join(", ") : "",
    source: pkg.repository || pkg.homepage || cratesUrl(pkg.name, pkg.version),
    roots: [path.dirname(pkg.manifest_path)],
  });
}
for (const packages of Object.values(npmLicenses)) {
  for (const pkg of packages) {
    records.push({
      ecosystem: "npm",
      name: pkg.name,
      version: [...pkg.versions].sort().join(", "),
      license: pkg.license || "UNKNOWN",
      authors: normalizeAuthor(pkg.author),
      source: pkg.homepage || npmUrl(pkg.name),
      roots: [...pkg.paths].sort(),
    });
  }
}
records.push({
  ecosystem: "Bundled",
  name: "CotypeX",
  version: "0.5.5 source snapshot",
  license: "MIT",
  authors: "CoTypeX contributors",
  source: "https://github.com/Shichien/CotypeX",
  roots: [path.join(root, "web", "typing")],
});
records.sort((left, right) => left.ecosystem.localeCompare(right.ecosystem)
  || left.name.localeCompare(right.name)
  || left.version.localeCompare(right.version));

const licenseTexts = new Map();
const packagesWithoutText = [];
for (const record of records) {
  const identity = `${record.ecosystem}:${record.name}@${record.version}`;
  let found = false;
  for (const packageRoot of record.roots) {
    for (const file of await findLicenseFiles(packageRoot)) {
      const content = normalizeText(await fs.readFile(file, "utf8"));
      if (!content) continue;
      found = true;
      const hash = createHash("sha256").update(content).digest("hex");
      const entry = licenseTexts.get(hash) ?? { content, packages: new Set() };
      entry.packages.add(identity);
      licenseTexts.set(hash, entry);
    }
  }
  if (!found) packagesWithoutText.push(identity);
}

const version = cargo.packages.find((pkg) => pkg.name === "leetcodex" && pkg.source === null)?.version ?? "unknown";
const lines = [
  "# Third-Party Notices",
  "",
  `Generated for Leetcodex ${version} from Cargo.lock and web/pnpm-lock.yaml.`,
  "Do not edit this file manually; run `node scripts/generate-third-party-notices.mjs`.",
  "",
  "## Dependency Inventory",
  "",
  "| Ecosystem | Package | Version | License | Authors | Source |",
  "| --- | --- | --- | --- | --- | --- |",
];
for (const record of records) {
  lines.push(`| ${escapeCell(record.ecosystem)} | ${escapeCell(record.name)} | ${escapeCell(record.version)} | ${escapeCell(record.license)} | ${escapeCell(record.authors)} | ${record.source ? `[source](${record.source})` : ""} |`);
}
lines.push("", "## License And Notice Texts", "");
const sortedTexts = [...licenseTexts.entries()].sort(([, left], [, right]) => [...left.packages][0].localeCompare([...right.packages][0]));
for (const [hash, entry] of sortedTexts) {
  lines.push(`### ${[...entry.packages].sort().join(", ")}`, "", `SHA-256: \`${hash}\``, "");
  lines.push(...entry.content.split("\n").map((line) => `    ${line}`), "");
}
if (packagesWithoutText.length > 0) {
  lines.push("## Metadata-Only License Declarations", "", "The following packages declare a license expression but do not ship a top-level license or notice file in the installed package:", "");
  for (const identity of packagesWithoutText.sort()) lines.push(`- ${identity}`);
  lines.push("");
}
const output = `${lines.join("\n").replace(/\n{3,}/g, "\n\n").trim()}\n`;

if (process.argv.includes("--check")) {
  const existing = await fs.readFile(outputPath, "utf8").catch(() => "");
  if (existing !== output) {
    throw new Error("THIRD_PARTY_NOTICES.md is stale; run node scripts/generate-third-party-notices.mjs");
  }
  console.log(`Third-party notices are current (${records.length} dependencies, ${licenseTexts.size} unique texts).`);
} else {
  await fs.writeFile(outputPath, output, "utf8");
  console.log(`Wrote ${outputPath} (${records.length} dependencies, ${licenseTexts.size} unique texts).`);
}

async function findLicenseFiles(directory) {
  const entries = await fs.readdir(directory, { withFileTypes: true }).catch(() => []);
  return entries
    .filter((entry) => entry.isFile() && /^(license|licence|copying|notice)(?:[._-].*)?$/i.test(entry.name))
    .map((entry) => path.join(directory, entry.name))
    .sort();
}

function normalizeText(value) {
  return value.replaceAll("\r\n", "\n").replaceAll("\r", "\n").trim();
}

function normalizeAuthor(value) {
  if (typeof value === "string") return value;
  if (!value || typeof value !== "object") return "";
  return [value.name, value.email].filter(Boolean).join(" ");
}

function escapeCell(value) {
  return String(value ?? "").replaceAll("|", "\\|").replaceAll("\n", " ");
}

function cratesUrl(name, version) {
  return `https://crates.io/crates/${encodeURIComponent(name)}/${encodeURIComponent(version)}`;
}

function npmUrl(name) {
  return `https://www.npmjs.com/package/${encodeURIComponent(name)}`;
}
